create table notification_requests (
    id              uuid primary key,
    idempotency_key varchar(255) unique,
    created_at      timestamptz not null
);

create table notifications (
    id                     uuid primary key,
    request_id             uuid not null references notification_requests (id),
    user_id                varchar(100) not null,
    order_id               uuid,
    channel                varchar(10) not null,
    template               varchar(30) not null,
    recipient_name         varchar(120) not null,
    recipient_email        varchar(254),
    recipient_phone        varchar(20),
    recipient_device_token varchar(255),
    subject                varchar(200) not null,
    body                   text not null,
    status                 varchar(10) not null,
    skip_reason            varchar(30),
    scheduled_at           timestamptz,
    sent_at                timestamptz,
    created_at             timestamptz not null,
    constraint notifications_channel_check check (channel in ('EMAIL', 'SMS', 'PUSH')),
    constraint notifications_status_check
        check (status in ('SCHEDULED', 'PENDING', 'RETRYING', 'SENT', 'FAILED', 'SKIPPED'))
);

create index notifications_request_idx on notifications (request_id);
create index notifications_user_idx on notifications (user_id, created_at desc);
create index notifications_order_idx on notifications (order_id) where order_id is not null;
create index notifications_due_idx on notifications (scheduled_at) where status = 'SCHEDULED';

create table notification_attempts (
    id              bigint generated by default as identity primary key,
    notification_id uuid not null references notifications (id),
    attempt_number  integer not null,
    attempted_at    timestamptz not null,
    success         boolean not null,
    error           varchar(500),
    -- Last line of defence against recording the same attempt twice.
    constraint notification_attempts_once unique (notification_id, attempt_number)
);

create table notification_preferences (
    user_id    varchar(100) primary key,
    email      boolean not null,
    sms        boolean not null,
    push       boolean not null,
    updated_at timestamptz not null
);

-- Messages waiting to be published to RabbitMQ. A row is written in the same transaction
-- as the change that causes it and removed once the broker confirms the message.
create table outbox (
    id              bigint generated by default as identity primary key,
    notification_id uuid not null,
    queue           varchar(100) not null,
    attempt         integer not null,
    created_at      timestamptz not null
);
